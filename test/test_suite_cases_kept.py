"""The speed work keeps every test case (WP-50 50-03, TR-50-03.1).

For each test file WP-50 50-03 changes -- the files moved to the batch
tier, the sweep classes that share renders, the render-cache users -- the
number of cases each test runs is counted from the module itself (imported,
not run): the product of its parametrize lists (module, class and method
marks), and for a test that loops over groups of probe ids, the probes in
its groups.  A fixture's params are not counted (the module does not
hold them).  ``FROZEN`` holds the counts read at the base; a lever that
drops a test, a parameter or a probe turns ``test_counts[<file>]`` red.
"""
import importlib.util
import inspect
import os
import sys

import pytest

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
if HERE not in sys.path:
    sys.path.insert(0, HERE)

#: Tests that loop over groups of probe ids inside one case: the
#: parametrize argument that holds each case's group.  The probes in the
#: groups are counted, not the groups.
PROBE_GROUP_ARGS = {
    ("test/test_size_units.py", "TestStataRatios::test_sizes"): "group",
    ("test/test_size_units.py", "TestStataRatios::test_label_offsets"): "group",
}


def _as_list(m):
    return list(m) if isinstance(m, (list, tuple)) else [m]


def _marks(obj):
    return _as_list(getattr(obj, "pytestmark", []))


def _class_marks(cls):
    """A class's marks and its bases' (pytest reads the MRO)."""
    out = []
    for c in cls.__mro__:
        out += _as_list(vars(c).get("pytestmark", []))
    return out


def _argvalues(mark):
    return mark.args[1] if len(mark.args) > 1 else mark.kwargs["argvalues"]


def _argnames(mark):
    names = mark.args[0] if mark.args else mark.kwargs["argnames"]
    if isinstance(names, str):
        names = [n.strip() for n in names.split(",") if n.strip()]
    return list(names)


def _cases(marks, group_arg=None):
    """The cases a test with *marks* runs: the product of its parametrize
    lists, or, with *group_arg*, the probes its groups hold."""
    n = 1
    for m in marks:
        if m.name != "parametrize":
            continue
        values = list(_argvalues(m))
        names = _argnames(m)
        if group_arg in names:
            i = names.index(group_arg)
            n *= sum(len((getattr(v, "values", None) or v)[i]) for v in values)
        else:
            n *= len(values)
    return n


def _import(rel):
    name = "_cases_kept_" + os.path.basename(rel)[:-3]
    if name in sys.modules:
        return sys.modules[name]
    spec = importlib.util.spec_from_file_location(name, os.path.join(ROOT, rel))
    mod = importlib.util.module_from_spec(spec)
    sys.modules[name] = mod
    spec.loader.exec_module(mod)
    return mod


def _collected(obj):
    return getattr(obj, "__test__", True)


def _class_counts(rel, cls, prefix, outer):
    counts = {}
    if not _collected(cls) or "__init__" in vars(cls):
        return counts
    marks = outer + _class_marks(cls)
    for name, member in inspect.getmembers(cls):
        if inspect.isclass(member) and name.startswith("Test"):
            counts.update(_class_counts(rel, member, prefix + name + "::",
                                        marks))
        elif name.startswith("test") and callable(member) \
                and _collected(member):
            node = prefix + name
            counts[node] = _cases(marks + _marks(member),
                                  PROBE_GROUP_ARGS.get((rel, node)))
    return counts


def live_counts(rel):
    """``{test name: cases}`` for the test file *rel* (``test/test_x.py``),
    read from the imported module."""
    mod = _import(rel)
    outer = _marks(mod)
    counts = {}
    for name, member in vars(mod).items():
        if inspect.isclass(member) and name.startswith("Test"):
            counts.update(_class_counts(rel, member, name + "::", outer))
        elif name.startswith("test") and inspect.isfunction(member) \
                and _collected(member):
            counts[name] = _cases(outer + _marks(member),
                                  PROBE_GROUP_ARGS.get((rel, name)))
    return counts


