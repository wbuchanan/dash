"""test_color_fidelity.py — dash's colour table must be Stata's colour table.

``dash scatter mpg weight, mcolor(eltblue)`` has to draw the blue Stata draws.
Measured against Stata's own ``<ado>/base/style/color-<name>.style`` files,
each of which sets the colour with a ``set rgb "R G B"`` line:

**52 of the 92 named colours were wrong.**

The grey ramp was the worst of it — ``gs10`` was ``#f0f0f0``, a near-white,
where Stata's is ``#a0a0a0``, a mid grey, and ``gs14``/``gs15`` were both pure
white. A scheme built on greys rendered as a white page. Twelve of the fifteen
s2color ``p#`` colours were wrong too, so the default palette of the default
scheme was not Stata's: ``eltblue`` was ``#b7c9e2`` against Stata's
``#82c0e9``, ``edkblue`` was CSS navy ``#00008b`` against Stata's ``#3e647d``,
``emerald`` ``#50a050`` against ``#2d6d66``.

The pattern is that the wrong values are plausible CSS colours — ``green``
was ``#00ff00``, the CSS keyword, where Stata's ``green`` is ``#008000`` —
which is why they never looked obviously broken.

Expected values come from ``test/fixtures/color_truth.json``, generated by
``scripts/extract_color_truth.py`` from those style files, so this runs on a
machine with no Stata.
"""
import json
import os
import sys

import pytest

_HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(_HERE, ".."))
sys.path.insert(0, _HERE)

from dash_render import OptionTranslator

_FIXTURE = os.path.join(_HERE, "fixtures", "color_truth.json")

pytestmark = pytest.mark.skipif(
    not os.path.exists(_FIXTURE),
    reason="test/fixtures/color_truth.json is missing",
)


@pytest.fixture(scope="module")
def truth():
    with open(_FIXTURE) as fh:
        return json.load(fh)["colors"]


def _names():
    if not os.path.exists(_FIXTURE):
        return []
    with open(_FIXTURE) as fh:
        return sorted(json.load(fh)["colors"])


class TestEveryStataColourIsTheColourStataDraws:

    @pytest.mark.parametrize("name", _names())
    def test_the_hex_matches_statas_style_file(self, name, truth):
        got = OptionTranslator._COLOR_MAP.get(name)
        want = truth[name]["hex"]
        assert got is not None, (
            f"Stata defines the colour {name!r} and dash does not know it"
        )
        assert got.lower() == want, (
            f"mcolor({name}) renders {got} where Stata draws {want} "
            f"(from {truth[name]['source']})"
        )

    def test_the_translator_returns_it_too(self, truth):
        """Not just the table — the function users' options go through."""
        for name, entry in truth.items():
            assert OptionTranslator.translate_mcolor(name).lower() == \
                entry["hex"], name


class TestTheGreyRamp:
    """gs0-gs16 is a monotone ramp; it was neither monotone nor Stata's."""

    def test_it_is_monotone_from_black_to_white(self):
        vals = []
        for i in range(17):
            hexv = OptionTranslator._COLOR_MAP[f"gs{i}"].lstrip("#")
            vals.append(int(hexv[0:2], 16))
        assert vals == sorted(vals), f"the ramp is not monotone: {vals}"
        assert len(set(vals)) == len(vals), (
            f"two steps of the ramp are the same grey: {vals}"
        )

    def test_it_is_grey(self):
        for i in range(17):
            hexv = OptionTranslator._COLOR_MAP[f"gs{i}"].lstrip("#")
            r, g, b = (int(hexv[j:j + 2], 16) for j in (0, 2, 4))
            assert r == g == b, f"gs{i} is #{hexv}, which is not grey"

    def test_gs10_is_a_mid_grey_not_a_near_white(self, truth):
        """The measurement that found it."""
        assert OptionTranslator._COLOR_MAP["gs10"].lower() == \
            truth["gs10"]["hex"] == "#a0a0a0"


class TestTheDefaultPalette:
    """s2color's p1-p15 are the colours most dashboards actually use."""

    _S2COLOR_P = [
        "navy", "maroon", "forest_green", "dkorange", "teal", "cranberry",
        "lavender", "khaki", "sienna", "emidblue", "emerald", "brown",
        "erose", "gold", "bluishgray",
    ]

    @pytest.mark.parametrize("name", _S2COLOR_P)
    def test_each_matches_stata(self, name, truth):
        assert OptionTranslator._COLOR_MAP[name].lower() == truth[name]["hex"]


class TestTheAliasesStillWork:
    """British spellings are dash's own convenience, not Stata names."""

    @pytest.mark.parametrize("alias,canonical", [
        ("grey", "gray"),
        ("dimgrey", "dimgray"),
        ("bluishgrey", "bluishgray"),
        ("ltbluishgrey", "ltbluishgray"),
    ])
    def test_an_alias_resolves_to_its_canonical_colour(self, alias, canonical):
        cm = OptionTranslator._COLOR_MAP
        assert cm[alias] == cm[canonical], (
            f"{alias} and {canonical} must be the same colour"
        )


class TestColourNone:
    """``none`` means draw nothing, which is not a colour at all.

    Stata's own ``color-none.style`` sets ``rgb "0 0 0"`` and then says
    ``* values should not matter`` — Stata never paints it.  dash previously
    mapped the name to white, which happened to be invisible on a white
    background and opaque everywhere else; taking Stata's file literally
    would paint it black.  Neither is what Stata draws.

    ``fcolor(none)`` was already handled correctly; ``mcolor``, ``lcolor``
    and ``mfcolor`` were not.
    """

    @staticmethod
    def _glyph(opts, ptype="scatter"):
        import json
        import tempfile

        import numpy as np
        import pandas as pd

        from dash_render import DashRenderer
        from conftest import make_spec, make_data_json

        df = pd.DataFrame({"mpg": np.linspace(12.0, 41.0, 12),
                           "weight": np.linspace(1760.0, 4840.0, 12)})
        spec = make_spec([{"type": ptype, "yvar": "mpg", "xvar": "weight",
                           "options": opts}])
        sp = tempfile.mkstemp(".json")[1]
        dp = tempfile.mkstemp(".json")[1]
        op = tempfile.mkstemp(".html")[1]
        with open(sp, "w") as f:
            json.dump(spec, f)
        with open(dp, "w") as f:
            json.dump(make_data_json(df), f)
        dr = DashRenderer(sp, dp, op)
        dr.render()
        for p in (sp, dp, op):
            try:
                os.unlink(p)
            except OSError:
                pass
        for fig in dr.figures.values():
            for r in fig.renderers:
                g = getattr(r, "glyph", None)
                if g is not None:
                    return g
        raise AssertionError("no glyph was built")

    def test_the_table_records_statas_own_value(self, truth):
        """Faithful to the file; the drawing is handled separately."""
        assert OptionTranslator._COLOR_MAP["none"].lower() == \
            truth["none"]["hex"]

    def test_mcolor_none_paints_nothing(self):
        g = self._glyph({"mcolor": "none"})
        assert float(getattr(g, "fill_alpha", 1.0)) == 0.0, (
            f"mcolor(none) painted {g.fill_color!r} at alpha {g.fill_alpha!r}"
        )

    def test_lcolor_none_paints_no_outline(self):
        g = self._glyph({"lcolor": "none"}, ptype="line")
        assert float(getattr(g, "line_alpha", 1.0)) == 0.0, (
            f"lcolor(none) drew a line at alpha {g.line_alpha!r}"
        )

    def test_an_ordinary_colour_is_unaffected(self):
        g = self._glyph({"mcolor": "navy"})
        assert str(g.fill_color).lower() == "#1a476f"
        assert float(getattr(g, "fill_alpha", 1.0)) > 0.0
