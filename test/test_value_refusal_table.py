"""twoway's return codes and words for the option values it refuses (WP-35
section 35-05, basic:PT-9).

dash_parse.mata's _dash_tw_value_tab() is generated by
scripts/gen_value_refusal_table.py from test/fixtures/value_truth.json and
test/fixtures/value_codes_truth.json (scripts/extract_value_codes_truth.do);
_dash_validate_value looks a refusal up there through _dash_tw_value_msg()
and prints twoway's first line with twoway's rc.  Mata runs only in Stata:
test_option_validation.cscript Q3505-1 and test_wp33_truth.cscript Q3310-1
run the lookup.
"""
import json
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GEN = os.path.join(ROOT, "scripts", "gen_value_refusal_table.py")
CODES = os.path.join(ROOT, "test", "fixtures", "value_codes_truth.json")


def _read(name):
    with open(os.path.join(ROOT, name), encoding="utf-8") as fh:
        return fh.read()


def _child_env():
    return {k: v for k, v in os.environ.items() if not k.startswith("PYTHON")}


class TestTheTable:
    def test_generated_and_in_step(self):
        # The table is the generator's output from both fixtures, and it
        # holds twoway's measured rows: base(abc) r(4026), bin(0) r(125),
        # mlabel(make..) r(101), rbar barwidth(.) r(199).
        r = subprocess.run([sys.executable, GEN, "--check"], cwd=ROOT,
                           env=_child_env(), capture_output=True, text=True)
        assert r.returncode == 0, r.stderr
        mata = _read("dash_parse.mata")
        body = mata[mata.index("// BEGIN tw_value"):mata.index("// END tw_value")]
        rows = re.findall(r't = t \\ \("([^"]*)", "([^"]*)", "([^"]*)", "([^"]*)", "([^"]*)"\)', body)
        got = {(o, c): (rc, line) for o, _t, c, rc, line in rows}
        assert got[("base", "nan")] == ("4026", "option base() incorrectly specified, %v is not a number")
        assert got[("bin", "below")][0] == "125"
        assert got[("mlabel", "dots")] == ("101", "factor-variable and time-series operators not allowed")
        assert got[("barwidth", "missing")] == ("199", "unrecognized command")
        with open(CODES, encoding="utf-8") as fh:
            fx = json.load(fh)
        assert fx["_meta"]["source"] == "scripts/extract_value_codes_truth.do"
        assert fx["probes"]["mlabel_dotdot"]["rc"] == 101
        assert fx["probes"]["rbar_barwidth_missing"]["rc"] == 199


class TestTheLookup:
    def test_defined_and_needed(self):
        # The lookup is a dash_parse.mata function, on _dash_require_mata's
        # _needed list and in the file header; _dash_validate_value calls
        # it at its refusal site and _dash_mlabel_list for mlabel(make..).
        mata = _read("dash_parse.mata")
        assert re.search(r"^string scalar _dash_tw_value_msg\(string scalar opt, "
                         r"string scalar ptype,\s+string scalar cls, string scalar value\)",
                         mata, re.M)
        assert "*!   _dash_tw_value_msg(opt, ptype, cls, value)" in mata
        ado = _read("dash.ado")
        req = ado[ado.index("program define _dash_require_mata"):]
        req = req[:req.index("\nend\n")]
        assert re.search(r"^\s+_dash_tw_value_msg ///$", req, re.M)
        for prog in ("_dash_validate_value", "_dash_mlabel_list"):
            body = ado[ado.index("program define %s," % prog):]
            body = body[:body.index("\nend\n")]
            assert body.count("_dash_tw_value_msg(") == 1, prog
