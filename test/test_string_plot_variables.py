"""GAPS2 G2: a string variable named as a plot variable is refused.

``twoway`` refuses a string x or y with r(109) -- its varlist parser
declares ``numeric`` (``twoway_yxview_parse.class``; ``histogram.ado`` and
``kdensity.ado`` declare ``varname(numeric)``) -- before it draws anything.
dash.ado's four varlist parsers did not declare ``numeric`` at all, and
dash_render.py had no check either: a string x drew meaningless Scatter,
Line or VBar glyphs with no note, and ``lfit``/``histogram`` crashed deep in
numpy with "could not convert string to float" (GAPS2 G2's measured
symptom).

This file pins the renderer-side half of the fix: a hand-written spec (or
one dash.ado wrote before this check existed) that names a string plot
variable is refused by both renderers with ``dash_render.DashSpecError``,
naming the variable, the layer type and r(109); ``colorvar()``,
``mlabel()``, ``hover()`` and ``by()`` still take a string.  The Stata-side
half -- dash.ado's own ``syntax varlist(numeric)`` refusal, measured
against ``twoway`` itself for every plot type and variable position -- is
pinned by the generated region of ``test/test_adversarial.cscript``
(SV-01..SV-87, produced by ``scripts/gen_string_varlists_cscript.py``),
not by pytest; ``TestTheGeneratedRegion`` below only checks that region is
present and current.
"""
import importlib.util
import os
import re
import sys

import pandas as pd
import pytest

_HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(_HERE, ".."))
sys.path.insert(0, _HERE)

import dash_render as dr  # noqa: E402
import test_mode_parity as tp  # noqa: E402

_ADVERSARIAL_CSCRIPT = os.path.join(_HERE, "test_adversarial.cscript")
_GENERATOR = os.path.join(
    _HERE, "..", "scripts", "gen_string_varlists_cscript.py")
_BEGIN_MARK = ("* ---- generated by scripts/gen_string_varlists_cscript.py: "
               "begin ----")
_END_MARK = ("* ---- generated by scripts/gen_string_varlists_cscript.py: "
             "end ----")


def _with_string_column(monkeypatch, colname="s",
                         values=("a", "b", "c", "d", "e", "f", "g", "h",
                                 "i", "j")):
    """Extend ``test_mode_parity``'s fixture frame with a string column and
    teach its data-json writer that the added column (and any other
    object-dtype column) is a Stata string variable.

    ``make_data_json`` (test/conftest.py:460-461) marks every column
    numeric unconditionally, on purpose -- no existing caller needed a
    string column -- so a plain ``monkeypatch.setattr(tp, "_DF", df)``
    alone is not enough; the writer itself is wrapped too.
    """
    df = tp._DF.copy()
    df[colname] = list(values)[: len(df)]
    monkeypatch.setattr(tp, "_DF", df)
    orig = tp.make_data_json

    def _patched(frame, *a, **kw):
        out = orig(frame, *a, **kw)
        sj = out["StataJSON"]
        for col in frame.columns:
            # pandas 3's default string dtype is "str", not "object": a
            # plain dtype-vs-object check (this file's first draft) never
            # matched, and every case appeared to render.
            if (pd.api.types.is_object_dtype(frame[col])
                    or pd.api.types.is_string_dtype(frame[col])):
                sj["variableTypeIsString"][col] = True
                sj["variableIsString"][col] = True
        return out

    monkeypatch.setattr(tp, "make_data_json", _patched)
    return df


def _plot(ptype, **fields):
    p = {"type": ptype, "options": {}}
    p.update(fields)
    return p


# One type per parser family (section-08 Evidence table), every variable
# key that family's parser reads.  "s" is the added string column; the
# other positions use plain numeric columns already in tp._DF.
_CASES = [
    ("scatter", "yvar", _plot("scatter", yvar="s", xvar="mpg")),
    ("scatter", "xvar", _plot("scatter", yvar="mpg", xvar="s")),
    ("histogram", "var", _plot("histogram", var="s")),
    ("rarea", "yvar1", _plot("rarea", yvar1="s", yvar2="mpg", xvar="weight")),
    ("rarea", "yvar2", _plot("rarea", yvar1="mpg", yvar2="s", xvar="weight")),
    ("rarea", "xvar", _plot("rarea", yvar1="mpg", yvar2="weight", xvar="s")),
    ("pcspike", "y1var", _plot("pcspike", y1var="s", x1var="mpg",
                               y2var="weight", x2var="price")),
    ("pcspike", "x1var", _plot("pcspike", y1var="mpg", x1var="s",
                               y2var="weight", x2var="price")),
    ("pcspike", "y2var", _plot("pcspike", y1var="mpg", x1var="weight",
                               y2var="s", x2var="price")),
    ("pcspike", "x2var", _plot("pcspike", y1var="mpg", x1var="weight",
                               y2var="price", x2var="s")),
    ("lfit", "yvar", _plot("lfit", yvar="s", xvar="mpg")),
    ("lfit", "xvar", _plot("lfit", yvar="mpg", xvar="s")),
    ("tsline", "yvar", _plot("tsline", yvar="s")),
]


class TestAStringPlotVariableIsRefused:

    @pytest.mark.parametrize(
        "ptype,key,plot", _CASES,
        ids=[f"{t}-{k}" for t, k, _ in _CASES])
    def test_in_both_modes(self, monkeypatch, ptype, key, plot):
        _with_string_column(monkeypatch)
        spec = tp._spec(plots=[plot])

        with pytest.raises(dr.DashSpecError) as exc_saved:
            tp._standalone(spec)
        saved_msg = str(exc_saved.value)
        assert "'s'" in saved_msg
        assert ptype in saved_msg
        assert "r(109)" in saved_msg

        with pytest.raises(dr.DashSpecError) as exc_served:
            tp._served(spec)
        served_msg = str(exc_served.value)
        assert "'s'" in served_msg
        assert ptype in served_msg
        assert "r(109)" in served_msg


@pytest.mark.parametrize("key", ["colorvar", "mlabel", "hover", "by"])
def test_a_string_in_an_option_is_not_refused(monkeypatch, key):
    """Control: colorvar(), mlabel(), hover() and by() still take a
    string variable in both renderers -- BR-08.2."""
    _with_string_column(monkeypatch)
    plot = _plot("scatter", yvar="mpg", xvar="weight")
    go = {}
    if key in ("colorvar", "mlabel"):
        plot["options"][key] = "s"
    elif key == "hover":
        go["hover"] = "s"
    elif key == "by":
        go["by"] = "s"
    spec = tp._spec(plots=[plot], graph_options=go)
    r, _w = tp._standalone(spec)
    assert any(name == "g1" or name.startswith("g1__by__")
              for name in r.figures)
    doc, _w2 = tp._served(spec)
    assert doc.roots


def test_the_message_is_bounded_and_escaped(monkeypatch):
    """A column name 200 characters long and carrying a control byte: the
    message is bounded and the control byte never reaches it raw, through
    ``_dash_display`` (rule 1) -- the same guard every other dash warning
    that echoes user text uses (``_dash_warn_filter_missing`` and
    friends), not an HTML escaper: this message never reaches a page."""
    long_name = ("s" + "x" * 40 + "\x07" + "y" * 200)[:200]
    _with_string_column(monkeypatch, colname=long_name,
                         values=["a"] * 10)
    spec = tp._spec(plots=[_plot("scatter", yvar=long_name, xvar="mpg")])
    with pytest.raises(dr.DashSpecError) as exc:
        tp._standalone(spec)
    msg = str(exc.value)
    assert "\x07" not in msg
    assert all(ch.isprintable() for ch in msg)
    assert len(msg) < 300


class TestTheGeneratedRegion:
    """TR-08.5: the generated region of test_adversarial.cscript is
    produced by scripts/gen_string_varlists_cscript.py and stays current."""

    @staticmethod
    def _region_text():
        with open(_ADVERSARIAL_CSCRIPT, encoding="utf-8") as fh:
            text = fh.read()
        if _BEGIN_MARK not in text or _END_MARK not in text:
            return None
        start = text.index(_BEGIN_MARK)
        end = text.index(_END_MARK) + len(_END_MARK)
        return text[start:end]

    @staticmethod
    def _generator():
        if not os.path.exists(_GENERATOR):
            return None
        spec = importlib.util.spec_from_file_location(
            "gen_string_varlists_cscript", _GENERATOR)
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
        return mod

    def test_the_region_is_current(self):
        mod = self._generator()
        region = self._region_text()
        if mod is None or region is None:
            pytest.fail("task 08-02 must land first")
        assert mod.render().strip() == region.strip()

    def test_it_covers_every_type_that_takes_variables(self):
        mod = self._generator()
        region = self._region_text()
        if mod is None or region is None:
            pytest.fail("task 08-02 must land first")
        # \d+ since WP-31 B4b took the cases past SV-99.
        call_ids = re.findall(r'_sv_case "SV-(\d+)"', region)
        n = mod.N_CASES
        assert len(call_ids) == n
        assert sorted(int(i) for i in call_ids) == list(range(1, n + 1))
        # The runtime PASS text is templated ("`sv'", already "SV-nn"),
        # not literal, so it names the case only once Stata expands the
        # macro; the template itself is what is checked here.
        assert "display as text \"`sv' PASS" in region
        types = mod.variable_taking_types()
        # 36 -> 38: WP-31 B1 rpcap and rpspike drawn.
        # 38 -> 40: WP-31 B4b contour and contourline drawn.
        assert len(types) == 40
        assert not ({"scatteri", "pci", "pcarrowi", "function"} & set(types))

    def test_the_arity_table_matches_dash_ado(self):
        mod = self._generator()
        if mod is None:
            pytest.fail("task 08-02 must land first")
        families = mod.read_plottype_families()
        assert set(families["_pt_univar"]) == {"histogram", "kdensity"}
        assert set(families["_pt_pc"]) == {
            "pcspike", "pcarrow", "pcbarrow", "pcscatter", "pccapsym"}
        assert set(families["_pt_literal"]) == {
            "scatteri", "pci", "pcarrowi", "function"}
        assert "tsrline" in families["_pt_range"]
        assert "tsline" in families["_pt_ts"]
