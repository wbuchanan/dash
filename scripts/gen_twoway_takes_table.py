#!/usr/bin/env python3
"""Generate dash_parse.mata's _dash_tw_takes_tab(): the option words twoway
takes that dash leaves to its catch-all.

WP-32 (BUGS.md "In a few mixed lists dash names another word than twoway
names first, and an unknown lower-case word is noted where twoway refuses
it").  One row per probe of test/fixtures/unknown_option_truth.json that
twoway takes (rc 0, or play()'s r(601) for a file it then cannot find):
its full name, its shortest spelling (the shortest from which every longer
spelling is taken), 1 when it takes a value, the plot types it is taken on
("*" for all forty-four) and 1 when it is taken after the plot groups'
comma.  Written between the ``// BEGIN tw_takes`` and ``// END tw_takes``
markers, never typed by hand.

WP-32 (BUGS.md "dash names in its note, as not drawn, options twoway
refuses on that plot type"): dash_parse.mata's _dash_tw_refuses_tab(), the
options dash declares (DECLARED, with the shortest spelling dash's -syntax-
binds to each) that twoway refuses, from test/fixtures/noted_option_truth.json:
one row per such option -- its full name, dash's shortest spelling, the plot
types twoway refuses it on ("*" for all forty-four) and 1 when it refuses it
after the plot groups' comma -- between ``// BEGIN tw_refuses`` and
``// END tw_refuses``.

And _dash_tw_silent_tab(), the options on dash's pending lists (SILENT)
that twoway takes and draws nothing different with: one row per option,
its name and the plot types where the fixture's twoway_draws is false (the
same picture), between ``// BEGIN tw_silent`` and ``// END tw_silent``.
dash takes each there without a note.  sort is the types both its probes
(sort and sort(price)) draw the same on.

    python3 scripts/gen_twoway_takes_table.py          # rewrite dash_parse.mata
    python3 scripts/gen_twoway_takes_table.py --check  # exit 1 if stale
"""
import argparse
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FIXTURE = os.path.join(ROOT, "test", "fixtures", "unknown_option_truth.json")
MATA = os.path.join(ROOT, "dash_parse.mata")
BEGIN = ("    // BEGIN tw_takes (generated by scripts/gen_twoway_takes_table.py"
         " from test/fixtures/unknown_option_truth.json; do not edit)")
END = "    // END tw_takes"
TAKEN = (0, 601)
NOTED = os.path.join(ROOT, "test", "fixtures", "noted_option_truth.json")
RBEGIN = ("    // BEGIN tw_refuses (generated by scripts/gen_twoway_takes_table.py"
          " from test/fixtures/noted_option_truth.json; do not edit)")
REND = "    // END tw_refuses"
# The options dash's plot parser declares and named in its note as not
# drawn, each with the shortest spelling -syntax- binds to it (its
# capitalised minimum in _dash_parse_plot_opts; test_noted_options.py
# reads them back out of dash.ado).
DECLARED = {"at": "at", "blabel": "blabel", "ciopts": "ciopts",
            "fitopts": "fitopts", "lineopts": "lineopts",
            "mlabwidth": "mlabw", "filter": "filt", "link": "link",
            "headlabel": "head"}


def rows(fx):
    """(full, shortest, value, types, after_comma) for each taken probe."""
    out = []
    types = fx["types"]
    for name in sorted(fx["probes"]):
        p = fx["probes"][name]
        if p["twoway_rc"] not in TAKEN:
            continue
        opt = p["option"]
        full = opt.split("(", 1)[0]
        value = "1" if "(" in opt else "0"
        sp = p["spellings_rc"]
        L = len(full)
        for j in range(len(sp) - 1, -1, -1):
            if sp[j] in TAKEN:
                L = j + 1
            else:
                break
        tt = p["types_taking"]
        ts = "*" if len(tt) == len(types) else " ".join(tt)
        ac = "1" if p.get("after_comma_rc") in TAKEN else "0"
        out.append((full, full[:L], value, ts, ac))
    return out


def refused_rows(nx):
    """(full, shortest, types, after_comma) for each DECLARED option twoway
    refuses on some type."""
    types = nx["types"]
    out = []
    for opt in sorted(nx["probes"]):
        full = opt.split("(", 1)[0]
        if full not in DECLARED:
            continue
        rows = nx["probes"][opt]
        ref = [t for t in types if rows[t]["twoway_rc"] == 198]
        if not ref:
            continue
        ts = "*" if len(ref) == len(types) else " ".join(ref)
        ac = "0"
        for g in nx["graph_level"]:
            if (g["cmd"].startswith("(scatter mpg weight), ")
                    and g["cmd"].split(", ", 1)[1].split("(", 1)[0] == full
                    and g["twoway_rc"] == 198):
                ac = "1"
        out.append((full, DECLARED[full], ts, ac))
    return out


SBEGIN = ("    // BEGIN tw_silent (generated by scripts/gen_twoway_takes_table.py"
          " from test/fixtures/noted_option_truth.json; do not edit)")
SEND = "    // END tw_silent"
SILENT = ("acolor", "alcolor", "alwidth", "alpattern", "bmlinestyle",
          "dlalign", "mangle", "barbsize", "headlabel", "msize", "recast",
          "sort", "heatmap", "outlines", "lstyle", "alstyle", "blstyle",
          "mstyle", "mlstyle", "mwidth", "baroffset")


def silent_rows(nx):
    """(name, types) for each SILENT option: the types twoway takes it on
    and draws the same picture with."""
    types = nx["types"]
    by = {}
    for opt in sorted(nx["probes"]):
        name = opt.split("(", 1)[0]
        if name not in SILENT:
            continue
        rows = nx["probes"][opt]
        same = {t for t in types
                if rows[t]["twoway_rc"] == 0 and rows[t]["twoway_draws"] is False}
        by[name] = same if name not in by else by[name] & same
    out = []
    for name in sorted(by):
        if by[name]:
            out.append((name, " ".join(t for t in types if t in by[name])))
    return out


def sblock(nx):
    lines = [SBEGIN]
    for r in silent_rows(nx):
        lines.append('    t = t \\ ("%s", "%s")' % r)
    lines.append(SEND)
    return lines


def rblock(nx):
    lines = [RBEGIN]
    for r in refused_rows(nx):
        lines.append('    t = t \\ ("%s", "%s", "%s", "%s")' % r)
    lines.append(REND)
    return lines


def block(fx):
    lines = [BEGIN]
    for r in rows(fx):
        lines.append('    t = t \\ ("%s", "%s", "%s", "%s", "%s")' % r)
    lines.append(END)
    return lines


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    with open(FIXTURE, encoding="utf-8") as fh:
        fx = json.load(fh)
    with open(MATA, encoding="utf-8") as fh:
        text = fh.read()
    with open(NOTED, encoding="utf-8") as fh:
        nx = json.load(fh)
    lines = text.split("\n")
    i, j = lines.index(BEGIN), lines.index(END)
    new = lines[:i] + block(fx) + lines[j + 1:]
    i, j = new.index(RBEGIN), new.index(REND)
    new = new[:i] + rblock(nx) + new[j + 1:]
    i, j = new.index(SBEGIN), new.index(SEND)
    new = new[:i] + sblock(nx) + new[j + 1:]
    if a.check:
        if new != lines:
            print("dash_parse.mata's tw_takes, tw_refuses or tw_silent table is stale; run "
                  "scripts/gen_twoway_takes_table.py", file=sys.stderr)
            return 1
        return 0
    with open(MATA, "w", encoding="utf-8") as fh:
        fh.write("\n".join(new))
    return 0


if __name__ == "__main__":
    sys.exit(main())
