#!/usr/bin/env python3
"""Regenerate the generated region of test/test_adversarial.cscript
(GAPS2 G2, WP-28 section 08).

twoway refuses a string plot variable with r(109) -- its own varlist
parsers declare ``numeric`` (twoway_yxview_parse.class for the y/x family;
histogram.ado and kdensity.ado declare ``varname(numeric)``).  dash.ado's
four varlist parsers (``_dash_parse_varpart_std/_1v/_3v/_4v``) now declare
``numeric`` too, so a string plot variable is refused the same way, before
any count check runs.  This script writes ONE case per (plot type,
variable position) of every type that takes variables -- read from
dash_parse.mata's ``_expand_plottype_str`` table and dash.ado's
``_dash_plottype_families`` -- into the marked region of
test/test_adversarial.cscript.  It never types twoway's wording by hand:
every case measures it live, in the same run, against dash's own output.

Usage:
    python3 scripts/gen_string_varlists_cscript.py            # rewrite
    python3 scripts/gen_string_varlists_cscript.py --check     # verify only

Measured once, live, for one representative of each family that takes
variables (probe run, 25sep2026, sysuse auto): every one of them --
scatter, histogram, rarea, pcspike, tsline, tsrline and lfit -- printed
the identical two lines and rc:

    r(109): "string variables not allowed in varlist;" / "<name> is a
             string variable"

This is Stata's own ``syntax ... numeric ...`` message, not a per-command
one, so nothing here special-cases a family's wording; the header above is
a record for the reader, and every case below asserts equality with
twoway's OWN log line for that exact command, measured in the same run.
The four literal types (scatteri, pci, pcarrowi, function) take no
variable -- twoway reads literal coordinates or an expression there -- and
are not in this region at all: measured (same probe), ``twoway pci 0 0 0
make`` is r(198) "invalid point", not r(109), because "make" is read as a
literal token, never as a variable.

Case count: this section's plan text (`.ultraplan/sections/
section-08-numeric-varlists-and-data-limit.md`, TR-08.3) derives "89 cases
(20 x 2 + 2 x 1 + 8 x 3 + 1 x 2 + 5 x 4 + 1 x 1)".  Recomputing that sum
from the same families used here gives a different total: the "20 x 2"
term double-counts one type.  dash_parse.mata's plot-type table has 40
entries; four are literal (skipped); of the 36 that take variables,
_pt_univar has 2 (arity 1), _pt_pc has 5 (arity 4), _pt_range has 9 of
which tsrline is arity 2 and the other 8 are arity 3, and the remaining 20
dispatch through _dash_parse_varpart_std -- of which tsline alone is arity
1 and the other 19 (8 base types plus the 11 of _pt_onefit) are arity 2.
So the correct sum is 2x1 + 5x4 + 1x2 + 8x3 + 1x1 + 19x2 = 2+20+2+24+1+38
= 87, not 89 (the review process's own D10 fixed a similar arithmetic slip
in section 04; this is the same kind of correction, made here because
nothing caught it earlier).  N_CASES below is computed from the tables,
not from either hand count, so it is right by construction whichever
figure is correct.
"""
import argparse
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
MATA_PATH = os.path.join(HERE, "..", "dash_parse.mata")
ADO_PATH = os.path.join(HERE, "..", "dash.ado")
CSCRIPT_PATH = os.path.join(HERE, "..", "test", "test_adversarial.cscript")

BEGIN_MARK = ("* ---- generated by scripts/gen_string_varlists_cscript.py: "
              "begin ----")
END_MARK = ("* ---- generated by scripts/gen_string_varlists_cscript.py: "
            "end ----")

#: Filler variables for the positions NOT under test, in order (TR-08.3).
FILLERS = ["mpg", "weight", "price", "length"]


def read_plottype_table(mata_text=None):
    """[(full, min), ...] rows of _expand_plottype_str, in table order."""
    if mata_text is None:
        with open(MATA_PATH, encoding="utf-8") as fh:
            mata_text = fh.read()
    m = re.search(
        r"string scalar _expand_plottype_str.*?tbl\s*=\s*(.*?)\n(?=\s*//)",
        mata_text, re.S)
    if not m:
        raise RuntimeError(
            "gen_string_varlists_cscript: could not find the plot-type "
            "table in dash_parse.mata (_expand_plottype_str).")
    rows = re.findall(r'\(\s*"([a-z0-9]+)"\s*,\s*"([a-z0-9]+)"\s*\)',
                       m.group(1))
    if len(rows) < 2:
        raise RuntimeError(
            "gen_string_varlists_cscript: found only %d plot-type rows; "
            "the table's shape must have changed." % len(rows))
    return rows


def read_plottype_families(ado_text=None):
    """{c_local name: [word, ...]} from dash.ado's _dash_plottype_families."""
    if ado_text is None:
        with open(ADO_PATH, encoding="utf-8") as fh:
            ado_text = fh.read()
    fams = dict(re.findall(r'c_local\s+(_pt_\w+)\s+"([^"]*)"', ado_text))
    if "_pt_univar" not in fams or "_pt_range" not in fams:
        raise RuntimeError(
            "gen_string_varlists_cscript: could not find "
            "_dash_plottype_families' c_local lines in dash.ado.")
    return {k: v.split() for k, v in fams.items()}


def type_arity(full, families):
    """The number of variables *full* takes, or ``None`` for a literal
    type that takes none (scatteri, pci, pcarrowi, function -- read as
    coordinates or an expression, never checked here)."""
    if full in families.get("_pt_literal", ()):
        return None
    if full in families.get("_pt_univar", ()):
        return 1
    if full in families.get("_pt_pc", ()):
        return 4
    if full == "tsrline":
        return 2
    if full in families.get("_pt_range", ()):
        return 3
    if full == "tsline":
        return 1
    return 2


def build_cases(table=None, families=None):
    """[(sv_id, ptype, position, [vars...]), ...] in table, then position,
    order; sv_id is 1-based."""
    if table is None:
        table = read_plottype_table()
    if families is None:
        families = read_plottype_families()
    cases = []
    sv = 0
    for full, _min in table:
        arity = type_arity(full, families)
        if arity is None:
            continue
        for pos in range(1, arity + 1):
            sv += 1
            fillers = iter(FILLERS)
            words = [
                "make" if slot == pos else next(fillers)
                for slot in range(1, arity + 1)
            ]
            cases.append((sv, full, pos, words))
    return cases


def variable_taking_types(table=None, families=None):
    """The 36 plot types tested here, in table order."""
    if table is None:
        table = read_plottype_table()
    if families is None:
        families = read_plottype_families()
    return [full for full, _min in table
            if type_arity(full, families) is not None]


N_CASES = len(build_cases())


def _header():
    lines = [
        BEGIN_MARK,
        "* GAPS2 G2 (WP-28 section 08): a string plot variable is",
        "* refused by dash exactly as twoway refuses it -- rc and words,",
        "* measured live against twoway's own log in the same run, never",
        "* typed here.  Generated by scripts/gen_string_varlists_cscript.py;",
        "* hand edits between the markers are undone by the next run.",
        "*",
        "* Measured once (25sep2026, sysuse auto), for one type of each",
        "* variable-taking family: scatter, histogram, rarea, pcspike,",
        "* tsline, tsrline and lfit all print the SAME two lines and rc --",
        '* r(109): "string variables not allowed in varlist;" /',
        '* "<name> is a string variable" -- because this is syntax\'s own',
        "* numeric-varlist message, not a per-command one.  A literal type",
        "* (scatteri, pci, pcarrowi, function) takes no case: measured, a",
        '* string token there is read as a coordinate or an expression,',
        '* not a variable ("invalid point", r(198), never r(109)).',
        "*",
        "* Case count derivation: see this generator's module docstring.",
    ]
    return "\n".join(lines)


def _mata_block():
    return "\n".join([
        "capture mata: mata drop _sv_lines()",
        "mata:",
        "string scalar _sv_lines(string scalar fn)",
        "{",
        "    real scalar   fh",
        "    string scalar line, full, out",
        '    fh = fopen(fn, "r")',
        '    out = ""',
        '    full = ""',
        '    while ((line = fget(fh)) != J(0, 0, "")) {',
        '        if (substr(line, 1, 2) == "> ") {',
        "            full = full + substr(line, 3, .)",
        "            continue",
        "        }",
        '        if (full != "") out = _sv_keep(out, full)',
        "        full = line",
        "    }",
        '    if (full != "") out = _sv_keep(out, full)',
        "    fclose(fh)",
        "    return(out)",
        "}",
        "",
        "string scalar _sv_keep(string scalar out, string scalar full)",
        "{",
        '    if (substr(full, 1, 2) == ". ") return(out)',
        '    if (regexm(full, "^r\\([0-9]+\\);$")) return(out)',
        '    return(out + (out == "" ? "" : char(10)) + full)',
        "}",
        "end",
    ])


def _sv_case_program():
    return "\n".join([
        "capture program drop _sv_case",
        "program define _sv_case, rclass",
        "    version 16.0",
        "    args sv ptype pos vars",
        '    local logfile "`c(tmpdir)\'dash_sv.log"',
        "    local ls = c(linesize)",
        "    set linesize 255",
        "",
        "    capture log close _svlog",
        '    capture erase "`logfile\'"',
        '    quietly log using "`logfile\'", name(_svlog) text replace',
        "    capture noisily twoway `ptype' `vars'",
        "    local tw_rc = _rc",
        "    quietly log close _svlog",
        '    mata: st_local("tw_txt", _sv_lines("`logfile\'"))',
        "",
        "    capture log close _svlog",
        '    capture erase "`logfile\'"',
        '    quietly log using "`logfile\'", name(_svlog) text replace',
        "    capture noisily dash `ptype' `vars', name(sv)",
        "    local dash_rc = _rc",
        "    quietly log close _svlog",
        '    mata: st_local("dash_txt", _sv_lines("`logfile\'"))',
        "    // The graph is never registered when it is refused: checked",
        "    // by name (not `: all globals \"dash_json_*\"') so a global",
        "    // some earlier, unrelated case in this 2,700-line script",
        "    // left behind cannot be misread as this case's leftover.",
        '    local leftover = "${dash_json_sv}"',
        "    capture dash clear",
        "    set linesize `ls'",
        '    capture erase "`logfile\'"',
        "",
        "    if `tw_rc' != 109 {",
        '        display as error "GENERATOR BUG: twoway `ptype\' `vars\' ' +
        'returned `tw_rc\', not 109 (wrong arity for this type)."',
        "        exit 9",
        "    }",
        "    assert `dash_rc' == `tw_rc'",
        '    assert `"`dash_txt\'"\' == `"`tw_txt\'"\'',
        '    assert "`leftover\'" == ""',
        '    display as text "`sv\' PASS: `ptype\', position `pos\' -- ' +
        'twoway\'s r(109) and words"',
        "end",
    ])


def _case_lines(cases):
    out = []
    for sv, ptype, pos, words in cases:
        sv_s = "SV-%02d" % sv
        vars_s = " ".join(words)
        out.append(
            '_sv_case "%s" "%s" %d "%s"' % (sv_s, ptype, pos, vars_s))
    return "\n".join(out)


def render():
    """The full text of the generated region, markers included."""
    cases = build_cases()
    parts = [
        _header(),
        "",
        "preserve",
        "capture dash clear",
        "sysuse auto, clear",
        "generate t = _n",
        "tsset t",
        "",
        _mata_block(),
        "",
        _sv_case_program(),
        "",
        _case_lines(cases),
        "",
        "capture program drop _sv_case",
        "capture dash clear",
        "restore",
        "",
        END_MARK,
    ]
    return "\n".join(parts) + "\n"


def write(check=False):
    with open(CSCRIPT_PATH, encoding="utf-8") as fh:
        text = fh.read()
    if BEGIN_MARK not in text or END_MARK not in text:
        raise RuntimeError(
            "gen_string_varlists_cscript: markers not found in %s; "
            "insert them once, by hand, before running this script."
            % CSCRIPT_PATH)
    start = text.index(BEGIN_MARK)
    end = text.index(END_MARK) + len(END_MARK)
    new_region = render().rstrip("\n")
    new_text = text[:start] + new_region + text[end:]
    if check:
        return new_text == text
    if new_text != text:
        with open(CSCRIPT_PATH, "w", encoding="utf-8") as fh:
            fh.write(new_text)
    return True


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                     help="exit 1 if the region on disk is not current")
    args = ap.parse_args()
    if args.check:
        ok = write(check=True)
        if not ok:
            print("gen_string_varlists_cscript: region is stale; "
                  "run without --check to rewrite it.")
            raise SystemExit(1)
        print("gen_string_varlists_cscript: region is current "
              "(%d cases)." % N_CASES)
        return
    write(check=False)
    print("gen_string_varlists_cscript: wrote %d cases to %s"
          % (N_CASES, os.path.normpath(CSCRIPT_PATH)))


if __name__ == "__main__":
    main()
