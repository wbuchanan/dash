#!/usr/bin/env python3
"""Generate the applicability table of dash.ado's _dash_option_rules.

WP-31 C3.  The table lists, per value option, the plot types twoway
accepts it on (every pair of test/fixtures/applicability_truth.json but
those refused r(198) "option <opt>() not allowed", measured by
scripts/extract_applicability_truth.do).  It is written between the
``// BEGIN applies`` and ``// END applies`` markers, never typed by hand.

    python3 scripts/gen_applicability_table.py          # rewrite dash.ado
    python3 scripts/gen_applicability_table.py --check  # exit 1 if stale
"""
import argparse
import difflib
import json
import os
import sys

OPTIONS = ("kernel", "n", "level", "bwidth", "bands", "range", "base",
           "degree", "bin", "width", "start", "barwidth", "ndots", "dotextend")
TYPES = ("scatter", "line", "connected", "area", "bar", "spike", "dropline",
         "dot", "tsline", "tsrline", "rarea", "rbar", "rspike", "rcap",
         "rline", "rconnected", "rcapsym", "rscatter", "rpcap", "rpspike",
         "pcspike", "pccapsym",
         "pcarrow", "pcbarrow", "pcscatter", "pci", "pcarrowi", "scatteri",
         "lfit", "qfit", "lfitci", "qfitci", "fpfit", "fpfitci", "lowess",
         "lpoly", "lpolyci", "mspline", "mband", "kdensity", "histogram",
         "function")

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FIXTURE = os.path.join(ROOT, "test", "fixtures", "applicability_truth.json")
ADO = os.path.join(ROOT, "dash.ado")
BEGIN = ("    // BEGIN applies (generated by scripts/gen_applicability_table.py"
         " from test/fixtures/applicability_truth.json; do not edit)")
END = "    // END applies"


def table(pairs):
    """The generated lines: ``local applies ///`` and one per option."""
    rows = []
    for opt in OPTIONS:
        # A pair applies unless twoway's syntax refused it (D-04.b): any
        # other answer, rc 0 or a class's message on the value, means the
        # type declares the option.
        types = [t for t in TYPES
                 if not (pairs[f"{opt}@{t}"]["rc"] == 198
                         and pairs[f"{opt}@{t}"]["message"]
                         == f"option {opt}() not allowed")]
        rows.append(f"        {opt}@{'|'.join(types)}")
    body = [r + " ///" for r in rows[:-1]] + rows[-1:]
    return ["    local applies ///"] + body


def splice(src, lines):
    """dash.ado's text with the block between the markers replaced."""
    i = src.index(BEGIN + "\n") + len(BEGIN) + 1
    j = src.index(END + "\n", i)
    return src[:i] + "\n".join(lines) + "\n" + src[j:]


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true",
                    help="print the block and exit 1 if dash.ado differs")
    args = ap.parse_args(argv)
    with open(FIXTURE, encoding="utf-8") as fh:
        pairs = json.load(fh)["pairs"]
    with open(ADO, encoding="utf-8") as fh:
        src = fh.read()
    lines = table(pairs)
    new = splice(src, lines)
    if args.check:
        print("\n".join(lines))
        if new != src:
            sys.stdout.writelines(difflib.unified_diff(
                src.splitlines(True), new.splitlines(True),
                "dash.ado", "dash.ado (generated)"))
            return 1
        return 0
    if new != src:
        with open(ADO, "w", encoding="utf-8") as fh:
            fh.write(new)
    return 0


if __name__ == "__main__":
    sys.exit(main())
