#!/usr/bin/env python3
"""Generate dash_parse.mata's _dash_tw_value_tab(): twoway's return code and
first line for each option value it refuses (WP-35 section 35-05,
basic:PT-9).

One row per (option, plot types, class): the option's name, the plot types
the row holds on ("*" for every type, else "type|type"), the class of the
failing value, twoway's rc and its first line, ``%v`` standing for the value
as typed.  Read from test/fixtures/value_truth.json (its refused probes,
first lines from value_codes_truth.json's ``vt_first``) and
test/fixtures/value_codes_truth.json (``probes`` and ``per_type``).  The
class of a probe is what dash.ado's _dash_validate_value computes for the
value under the option's rule in _dash_option_rules:

    missing  the value is "."
    nan      not a number (a word, a malformed number)
    huge     a number beyond Stata's double range (1e308)
    inf      a number beyond the machine's double range (1e400)
    nonint   not an integer, for an integer rule
    below    under the rule's lower bound (a positive rule: 0 or less)
    above    over the rule's upper bound
    dots     a variable name followed by .. (mlabel(make..))

A probe whose option has no value rule, or whose value the rule takes, is
left out (another program refuses it).  A class twoway answers alike on
every type measured, and accepts on none, is one "*" row; otherwise one row
per distinct answer naming its types.  Written between ``// BEGIN
tw_value`` and ``// END tw_value``, never typed by hand.

    python3 scripts/gen_value_refusal_table.py          # rewrite dash_parse.mata
    python3 scripts/gen_value_refusal_table.py --check  # exit 1 if stale
"""
import argparse
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VALUE = os.path.join(ROOT, "test", "fixtures", "value_truth.json")
CODES = os.path.join(ROOT, "test", "fixtures", "value_codes_truth.json")
ADO = os.path.join(ROOT, "dash.ado")
MATA = os.path.join(ROOT, "dash_parse.mata")
BEGIN = ("    // BEGIN tw_value (generated by scripts/gen_value_refusal_table.py"
         " from test/fixtures/value_truth.json and"
         " test/fixtures/value_codes_truth.json; do not edit)")
END = "    // END tw_value"
#: Stata's largest double, c(maxdouble).
MAXDOUBLE = 8.98846567431158e307
#: The per_type sets: option and the value probed.
PER_TYPE = {"lwidth_neg": ("lwidth", "-1"), "mlwidth_neg": ("mlwidth", "-1"),
            "msangle_400": ("msangle", "400")}
#: value_codes_truth.json probes whose class is not read from the value.
CLASS = {"mlabel_dotdot": "dots"}
_PLAIN = re.compile(r"^[-+]?([0-9]+\.?[0-9]*|\.[0-9]+)([eE][-+]?[0-9]+)?$")
_NUMLIKE = re.compile(r"^[-+.0-9eEdD]*[0-9][-+.0-9eEdD]*$")
_PROBE = re.compile(r"^twoway (\w+) .*\b(\w+)\(([^()]*)\)\s*$")


def rules(ado_text, types):
    """{(option, type): (spec, token types)} from _dash_option_rules' plot
    and graph locals, for each of *types* (type "@graph" for a graph
    rule).  The token types are the types the rule's token holds on: its
    @list, or for an untyped token every type no typed token of the option
    names; "*" for a graph rule."""
    typed, untyped, out = {}, {}, {}
    for name in ("plot", "graph"):
        m = re.search(r"\n    local %s ///\n((?:.*///\n)*.*\n)" % name, ado_text)
        body = m.group(1).replace("///", " ")
        for tok in body.split():
            if "=" not in tok:
                continue
            opt, rest = tok.split("=", 1)
            spec, _, ts = rest.partition("@")
            if name == "graph":
                out[(opt, "@graph")] = (spec, "*")
            elif ts:
                ts = tuple(t for t in ts.split("|")
                           if (opt, t) not in typed)
                for t in ts:
                    typed[(opt, t)] = (spec, "|".join(sorted(ts)))
            else:
                untyped.setdefault(opt, spec)
    for opt, spec in untyped.items():
        rest = tuple(t for t in types if (opt, t) not in typed)
        ts = "*" if len(rest) == len(types) else "|".join(sorted(rest))
        for t in rest:
            out[(opt, t)] = (spec, ts)
    out.update(typed)
    return out


def spec_for(rl, opt, ptype):
    """(spec, token types) of *opt*'s rule on *ptype*, or None."""
    return rl.get((opt, ptype)) or rl.get((opt, "@graph"))


def value_class(value, spec):
    """The class dash.ado gives *value* under *spec*, or None when the
    rule takes it."""
    parts = (spec.split(",") + ["", "", ""])[:4]
    kind, p1, p2, p3 = parts
    if kind not in ("num", "int", "pos", "style", "istyle", "enum"):
        return None
    v = value.strip()
    if kind == "enum":
        return None if v.lower() in p1.split("|") else "nan"
    if v == ".":
        return "missing"
    if not _PLAIN.match(v):
        if kind in ("style", "istyle") and not _NUMLIKE.match(v):
            return None
        if _NUMLIKE.match(v):
            try:
                x = float(v.replace("d", "e").replace("D", "e"))
            except ValueError:
                return "nan"
            return "inf" if x in (float("inf"), float("-inf")) else "huge"
        return "nan"
    x = float(v)
    if abs(x) > MAXDOUBLE:
        return "huge"
    if kind in ("int", "istyle") and x != int(x):
        return "nonint"
    if kind == "pos" and x <= 0:
        return "below"
    lo = float(p1) if p1 else None
    hi = float(p2) if p2 else None
    if kind == "pos":
        lo, hi = None, (float(p1) if p1 else None)
    if lo is not None and (x <= lo if p3 == "x" else x < lo):
        return "below"
    if hi is not None and (x >= hi if p3 == "x" else x > hi):
        return "above"
    return None


def with_v(line, value):
    """*line* with each whole-token occurrence of *value* as ``%v``."""
    v = value.strip()
    if not v:
        return line
    return re.sub(r"(?<![\w.])%s(?![\w.])" % re.escape(v), "%v", line)


def observations(vx, cx, rl):
    """[(option, class, token types, type, rc, line)] -- an rc 0 row says
    twoway took the value on that type."""
    obs = []
    first = cx["vt_first"]
    for p in vx["twoway"]:
        if not p["rc"]:
            continue
        ptype = p["command"].split()[1]
        rule = spec_for(rl, p["option"], ptype)
        if rule is None:
            continue
        cls = value_class(p["value"], rule[0])
        if cls is None:
            continue
        obs.append((p["option"], cls, rule[1], ptype, p["rc"],
                    with_v(first[p["id"]], p["value"])))
    for key in sorted(cx["probes"]):
        p = cx["probes"][key]
        if "reference" in p:
            continue
        m = _PROBE.match(p["command"])
        if not m:
            continue
        ptype, opt, value = m.groups()
        rule = spec_for(rl, opt, ptype) or ("var", "*")
        cls = CLASS.get(key) or value_class(value, rule[0])
        if cls is None:
            continue
        obs.append((opt, cls, rule[1], ptype, p["rc"],
                    with_v(p["first"], value) if p["rc"] else ""))
    for key, (opt, value) in sorted(PER_TYPE.items()):
        for ptype, p in sorted(cx["per_type"][key].items()):
            rule = spec_for(rl, opt, ptype)
            cls = value_class(value, rule[0]) if rule else None
            if cls is None:
                continue
            obs.append((opt, cls, rule[1], ptype, p["rc"],
                        with_v(p["first"], value) if p["rc"] else ""))
    return obs


def table(vx, cx, rl):
    """[(option, types, class, rc, line)], sorted by option then class.
    One row per rule token and class when every type measured under it
    answers alike and none takes the value (the row holds on the token's
    types); otherwise one row per answer, on the types measured."""
    groups = {}
    for opt, cls, toks, ptype, rc, line in observations(vx, cx, rl):
        seen = groups.setdefault((opt, cls, toks), {})
        if ptype in seen and seen[ptype] != (rc, line):
            raise SystemExit("two answers for %s %s on %s: %r, %r"
                             % (opt, cls, ptype, seen[ptype], (rc, line)))
        seen[ptype] = (rc, line)
    rows = []
    for (opt, cls, toks) in sorted(groups):
        seen = groups[(opt, cls, toks)]
        answers = set(seen.values())
        if len(answers) == 1 and next(iter(answers))[0] != 0:
            rc, line = next(iter(answers))
            rows.append((opt, toks, cls, rc, line))
            continue
        for rc, line in sorted(a for a in answers if a[0] != 0):
            types = "|".join(sorted(t for t, a in seen.items()
                                    if a == (rc, line)))
            rows.append((opt, types, cls, rc, line))
    return sorted(rows, key=lambda r: (r[0], r[2], r[1]))


def block(rows):
    out = [BEGIN, "    t = J(0, 5, \"\")"]
    for opt, types, cls, rc, line in rows:
        for s in (opt, types, cls, line):
            if any(c in s for c in ('"', "\x60", "$", "\\")):
                raise SystemExit("a character Mata source cannot hold: %r" % s)
        out.append('    t = t \\ ("%s", "%s", "%s", "%d", "%s")'
                   % (opt, types, cls, rc, line))
    out.append(END)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    with open(VALUE, encoding="utf-8") as fh:
        vx = json.load(fh)
    with open(CODES, encoding="utf-8") as fh:
        cx = json.load(fh)
    with open(ADO, encoding="utf-8") as fh:
        rl = rules(fh.read(), cx["_meta"]["types"])
    with open(MATA, encoding="utf-8") as fh:
        text = fh.read()
    lines = text.split("\n")
    i, j = lines.index(BEGIN), lines.index(END)
    new = lines[:i] + block(table(vx, cx, rl)) + lines[j + 1:]
    if a.check:
        if new != lines:
            print("dash_parse.mata's tw_value table is stale; run "
                  "scripts/gen_value_refusal_table.py", file=sys.stderr)
            return 1
        return 0
    with open(MATA, "w", encoding="utf-8") as fh:
        fh.write("\n".join(new))
    return 0


if __name__ == "__main__":
    sys.exit(main())
